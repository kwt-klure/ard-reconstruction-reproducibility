#!/usr/bin/env python3
"""Extract saved AUC summaries, validate the printed table, and author pgfplots.

No simulations, fitting, or recomputation of the underlying statistics occurs.
Run with the repository's Python; then compile the generated TeX with pdflatex.
All outputs remain beside this script. Source hashes bind the extracted points.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import re


import argparse

DENSITIES = [("baseline", "8.53"), ("d15", "15"), ("d25", "25")]
METHODS = [
    ("Product", "Count product", "Count product"),
    ("Circular", "Circular", "Circular"),
    ("Nuclear_lambda0.25", r"Nuclear ($\lambda=0.25$)", r"Nuclear ($\lambda=0.25$)"),
    ("Nuclear_lambda1", r"Nuclear ($\lambda=1$)", r"Nuclear ($\lambda=1$)"),
    ("Nuclear_lambda4", r"Nuclear ($\lambda=4$)", r"Nuclear ($\lambda=4$)"),
    ("Q_uniform", r"Uniform $Q^{\mathrm{unif}}$", r"$Q^{\mathrm{unif}}$"),
    ("Q_oracle", r"Oracle $Q^{\mathrm{or}}$", r"$Q^{\mathrm{or}}$"),
]


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def render(HERE, SOURCE, TABLE):
    source_hash = sha256(SOURCE)
    table_hash = sha256(TABLE)
    summary = json.loads(SOURCE.read_text())
    table_text = TABLE.read_text()
    table_rows = {}
    for line in table_text.splitlines():
        fields = line.split(" & ")
        if len(fields) == 4 and any(fields[0] == method[2] for method in METHODS):
            values = [re.search(r"([0-9]+\.[0-9]+) \(([0-9]+\.[0-9]+)\)", f) for f in fields[1:]]
            assert all(values), line
            table_rows[fields[0]] = [(v[1], v[2]) for v in values]
    assert len(table_rows) == 7

    points = []
    for di, (density, density_label) in enumerate(DENSITIES):
        for mi, (model, display_label, table_label) in enumerate(METHODS):
            matches = [(index, row) for index, row in enumerate(summary["summary"])
                       if row["density"] == density and row["k"] == 8
                       and row["model"] == model and row["metric"] == "auc_V"]
            assert len(matches) == 1, (density, model, len(matches))
            source_index, row = matches[0]
            assert row["status"] == "complete" and row["n_valid"] == row["n_expected"] == 40
            assert row["n_missing"] == row["n_undefined"] == 0
            printed = table_rows[table_label][di]
            expected = (f'{row["mean"]:.3f}', f'{row["mcse"]:.4f}')
            assert printed == expected, (density, model, printed, expected)
            point = {key: row[key] for key in ("density", "k", "model", "metric", "mean", "mcse", "n_valid", "n_expected", "status")}
            point.update({
                "density_label_percent": density_label,
                "display_label_tex": display_label,
                "y": 7 - mi,
                "source_json_pointer": f"/summary/{source_index}",
                "error_bar_lower": row["mean"] - row["mcse"],
                "error_bar_upper": row["mean"] + row["mcse"],
                "table_mean": printed[0],
                "table_mcse": printed[1],
                "table_rounding_verified": True,
            })
            assert 0.5 < point["error_bar_lower"] < point["error_bar_upper"] < 1
            points.append(point)
    assert len(points) == 21

    caption = (
        "Mean AUC on the fully unresolved pair set $\\mathcal V$ for $K=8$, "
        "at target densities 8.53\\%, 15\\%, and 25\\%. Points are means over "
        "40 independent replicate blocks; horizontal bars show plus or minus one MCSE. "
        "The uniform feasible-graph score $Q^{\\mathrm{unif}}$ and the conditional "
        "oracle $Q^{\\mathrm{or}}$ are highlighted. All three panels use the same AUC scale."
    )
    binding = {
        "source": {"path": SOURCE.name, "sha256": source_hash},
        "printed_table": {"path": TABLE.name, "sha256": table_hash},
        "extraction": "Exact stored mean and mcse fields; k == 8 and metric == auc_V. No simulations or refits.",
        "independent_unit": summary["independent_unit"],
        "n_independent_blocks": summary["n_independent_blocks"],
        "uncertainty": "mean plus or minus one MCSE; not a confidence interval",
        "x_range": [0.5, 1.0],
        "figure_width_inches": 6.45,
        "figure_height_inches": 2.85,
        "caption_tex": caption,
        "validation": {"point_count": len(points), "all_source_rows_complete": True, "all_21_means_and_mcse_match_table_rounding": True},
        "points": points,
    }
    (HERE / "density-unresolved-auc-data.json").write_text(json.dumps(binding, indent=2) + "\n")
    (HERE / "density-unresolved-auc-caption.tex").write_text(caption + "\n")

    # Physical dimensions are explicit: no display-dependent resizing or rasterization.
    tex = [
        "% Generated by build_density_figure.py; do not edit plotted values by hand.",
        f"% SUMMARY.json SHA256: {source_hash}",
        f"% density-ranking.tex SHA256: {table_hash}",
        r"\documentclass[tikz,border=0pt]{standalone}",
        r"\usepackage[T1]{fontenc}",
        r"\usepackage{lmodern}",
        r"\usepackage{amsmath}",
        r"\usepackage{pgfplots}",
        r"\pgfplotsset{compat=1.18}",
        r"\definecolor{baseline}{HTML}{555555}",
        r"\definecolor{uniform}{HTML}{29618A}",
        r"\definecolor{oracle}{HTML}{9B7226}",
        r"\definecolor{guide}{HTML}{E5E5E5}",
        r"\begin{document}",
        r"\begin{tikzpicture}",
        r"\path[use as bounding box] (0,0) rectangle (6.45in,2.85in);",
        r"\pgfplotsset{density panel/.style={",
        r"scale only axis,width=1.39in,height=1.95in,",
        r"xmin=0.5,xmax=1.0,ymin=0.5,ymax=7.5,",
        r"xtick={0.5,0.6,0.7,0.8,0.9,1.0},",
        r"xticklabels={0.5,0.6,0.7,0.8,0.9,1.0},",
        r"ytick={1,2,3,4,5,6,7},ytick style={draw=none},",
        r"tick label style={font=\fontsize{8}{10}\selectfont,text=black!85},",
        r"yticklabel style={font=\fontsize{9}{11}\selectfont,inner xsep=4pt},",
        r"title style={font=\fontsize{10}{12}\selectfont,at={(0.5,1.03)},anchor=south},",
        r"axis x line*=bottom,axis y line*=left,axis line style={black!45,line width=0.4pt},",
        r"tick style={black!50,line width=0.4pt},tick align=outside,",
        r"xmajorgrids=true,grid style={guide,line width=0.35pt},",
        r"enlarge x limits=false,clip=false,",
        r"}}",
    ]
    for di, (density, density_label) in enumerate(DENSITIES):
        x = 1.55 + di * 1.67
        labels = ",".join("{" + item[1] + "}" for item in reversed(METHODS)) if di == 0 else ""
        tex.extend([
            rf"\begin{{axis}}[density panel,name=panel{di},at={{({x:.2f}in,0.58in)}},anchor=south west,",
            rf"yticklabels={{{labels}}}]",
            r"\draw[black!32,line width=0.4pt,densely dashed] (axis cs:0.5,0.5) -- (axis cs:0.5,7.5);",
        ])
        for p in [p for p in points if p["density"] == density]:
            color = "uniform" if p["model"] == "Q_uniform" else "oracle" if p["model"] == "Q_oracle" else "baseline"
            marker = "square*" if color == "uniform" else "diamond*" if color == "oracle" else "*"
            size = "1.55pt" if color != "baseline" else "1.25pt"
            tex.extend([
                rf"% {p['model']}: exact stored mean +/- one MCSE",
                rf"\addplot+[only marks,color={color},mark={marker},mark size={size},",
                r"mark options={solid},error bars/.cd,x dir=both,x explicit,",
                r"error bar style={line width=0.85pt},error mark options={line width=0.65pt,mark size=2.5pt}]",
                f"coordinates {{({p['mean']:.17g},{p['y']}) +- ({p['mcse']:.17g},0)}};",
            ])
        tex.extend([
            r"\end{axis}",
            rf"\node[font=\fontsize{{10}}{{12}}\selectfont,anchor=center] at ({x + 0.695:.3f}in,2.70in) {{Density {density_label}\%}};",
        ])
    tex.extend([
        r"\node[font=\fontsize{9}{11}\selectfont,anchor=center] at (3.91in,0.25in) {AUC on fully unresolved pairs ($\mathcal V$)};",
        r"\node[font=\fontsize{8}{10}\selectfont,text=black!75,anchor=south west] at (0.04in,0.00in) {$K=8$; 40 independent replicate blocks. Points: means; bars: $\pm$ one MCSE.};",
        r"\end{tikzpicture}",
        r"\end{document}",
    ])
    (HERE / "density-unresolved-auc.tex").write_text("\n".join(tex) + "\n")
    assert sha256(SOURCE) == source_hash and sha256(TABLE) == table_hash, "Inputs changed during extraction"
    print(json.dumps({"status": "verified", "points": len(points), "source_sha256": source_hash, "table_sha256": table_hash}, indent=2))


